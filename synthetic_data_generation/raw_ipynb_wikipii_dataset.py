def chunks(l, n):
    return [l[i:i+n] for i in range(0, len(l), n)]

def do_job(in_queue, queue):
    import logging
    logger = logging.getLogger()
    logger.setLevel(logging.INFO)
    while True:
        if in_queue.empty(): return
        url_list = in_queue.get()
        for url in url_list:
            queue.put(get_annotations(url))

