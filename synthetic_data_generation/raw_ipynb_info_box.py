            mask_str = ''
            for scrape in self.info_dict[entity_list['dict_key']]:
                doc = nlp(str(scrape))
                if doc.ents and doc.ents[0].label_ == 'DATE':
                    mask_str = mask_str + 'd'
                elif str(scrape) == '' or str(scrape) == ',':
                    mask_str = mask_str + 's'
